package com.streamify.app.jam

import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

/**
 * The 48-byte JamOpWire envelope: exact layout, frozen forever — a byte-level
 * contract shared with the native CRDT (applied through
 * StreamifyEngineBridge since UFFI-04) and pinned by the shared golden
 * fixture.
 */
class JamOpWireTest {

    private val op = JamOpWire(
        opId = 0x0102030405060708L,
        sender = -0x1122334455667788L, // exercises sign bit
        type = JamOpWire.OP_REORDER,
        policy = 1,
        cadId = 0x7FEDCBA987654321L,
        frac = 0.5,
        target = 42L
    )

    // ═════════════════════════════════════════════════════════════════
    // audit #44 P1-2 — shared golden vectors. The repo freezes TWO
    // 48-byte CRDT-op formats (this Kotlin envelope inside JamWire OP
    // frames; the Rust jam_crdt image for the Phase-2 MSG_CRDT_OP
    // surface). `fixtures/jam_golden_vectors.json` is the ONE canonical
    // source for both byte images, generated by the neutral third-party
    // scripts/generate_jam_golden_vectors.py from the documented layouts.
    // The Rust suite (test_jam_golden_vectors.rs) pins the rust_48
    // column; these tests pin the kotlin_48 column. Any byte-image drift
    // — field order, endianness, width — fails here loudly instead of
    // splitting the protocol stacks silently.
    // ═════════════════════════════════════════════════════════════════

    private fun goldenFixture(): JSONObject {
        // Gradle's JVM unit-test working directory varies by runner
        // (module dir on AGP, project root under some IDE invocations) —
        // resolve against the candidates rather than guessing one.
        val candidates = listOf(
            File("fixtures/jam_golden_vectors.json"),
            File("../fixtures/jam_golden_vectors.json"),
            File("../../fixtures/jam_golden_vectors.json"),
        )
        val file = candidates.firstOrNull { it.isFile }
            ?: throw IllegalStateException(
                "golden fixture not found (tried ${candidates.map { it.path }}) — " +
                    "run scripts/generate_jam_golden_vectors.py from the repo root"
            )
        return JSONObject(file.readText())
    }

    private fun hexToBytes(hex: String): ByteArray =
        ByteArray(hex.length / 2) { i ->
            ((Character.digit(hex[i * 2], 16) shl 4) or Character.digit(hex[i * 2 + 1], 16)).toByte()
        }

    private fun goldenOp(v: JSONObject): JamOpWire {
        val fields = v.getJSONObject("fields")
        return JamOpWire(
            opId = java.lang.Long.parseUnsignedLong(fields.getString("op_id").removePrefix("0x"), 16),
            sender = java.lang.Long.parseUnsignedLong(fields.getString("sender").removePrefix("0x"), 16),
            type = fields.getInt("op_type"),
            policy = fields.getInt("policy"),
            cadId = java.lang.Long.parseUnsignedLong(fields.getString("cad_id").removePrefix("0x"), 16),
            frac = Double.fromBits(
                java.lang.Long.parseUnsignedLong(fields.getString("frac_bits").removePrefix("0x"), 16)
            ),
            target = java.lang.Long.parseUnsignedLong(fields.getString("target").removePrefix("0x"), 16),
        )
    }

    @Test
    fun `kotlin wire image is bit-frozen by the shared golden fixture`() {
        val vectors = goldenFixture().getJSONArray("vectors")
        assertTrue("fixture carries no op vectors", vectors.length() > 0)
        for (i in 0 until vectors.length()) {
            val v = vectors.getJSONObject(i)
            val name = v.getString("name")
            val want = hexToBytes(v.getString("kotlin_48"))
            assertEquals("$name: kotlin_48 must be 48 bytes", 48, want.size)

            val golden = goldenOp(v)
            val packed = JamOpWire.pack(golden)
            assertArrayEquals(
                "$name: Kotlin wire image drifted from the golden fixture — a FROZEN " +
                    "format changed (see scripts/generate_jam_golden_vectors.py)",
                want, packed
            )

            // Round-trip through the production parser must also succeed:
            // the golden images are all valid sealed ops.
            assertNotNull("$name: golden image must unpack", JamOpWire.unpack(want))
            assertEquals("$name: unpacked fields must match the fixture", golden, JamOpWire.unpack(want))
        }
    }

    @Test
    fun `rust wire images are fixture-visible but not kotlin-parseable`() {
        // Anti-convergence canary (mirrors the Rust suite's check): the
        // two 48-byte formats are DIFFERENT frozen layouts. If unpack()
        // ever accepts a rust_48 image as a valid op, the stacks have
        // started converging without anyone updating the fixture and the
        // layout docs — fail loudly.
        val vectors = goldenFixture().getJSONArray("vectors")
        for (i in 0 until vectors.length()) {
            val v = vectors.getJSONObject(i)
            val name = v.getString("name")
            val rustBytes = hexToBytes(v.getString("rust_48"))
            val restored = JamOpWire.unpack(rustBytes)
            if (restored != null) {
                // It parsed — only acceptable if the image is NOT the same
                // op as the Kotlin golden bytes (i.e. it is a coincidental
                // byte-valid parse of a foreign layout, which unpack must
                // still reject for type/policy/frac validity in practice).
                val kotlinBytes = JamOpWire.pack(goldenOp(v))
                assertFalse(
                    "$name: rust_48 image parsed as the SAME Kotlin op — the two " +
                        "frozen formats have converged; update the fixture generator " +
                        "and both layout docs deliberately",
                    kotlinBytes.contentEquals(rustBytes)
                )
            }
        }
    }

    @Test
    fun `pack produces exactly 48 bytes`() {
        assertEquals(48, JamOpWire.pack(op).size)
    }

    @Test
    fun `layout matches the frozen little-endian spec`() {
        val b = ByteBuffer.wrap(JamOpWire.pack(op)).order(ByteOrder.LITTLE_ENDIAN)
        assertEquals(op.opId, b.long)
        assertEquals(op.sender, b.long)
        assertEquals(op.type, b.int)
        assertEquals(op.policy, b.int)
        assertEquals(op.cadId, b.long)
        assertEquals(op.frac.toRawBits(), b.long)
        assertEquals(op.target, b.long)
        assertEquals(0, b.remaining())
    }

    @Test
    fun `unpack round-trips every field`() {
        val restored = JamOpWire.unpack(JamOpWire.pack(op))
        assertEquals(op, restored)
    }

    @Test
    fun `packing is canonical — identical ops produce identical bytes`() {
        assertArrayEquals(JamOpWire.pack(op), JamOpWire.pack(op.copy()))
    }

    @Test
    fun `wrong size rejected`() {
        assertNull(JamOpWire.unpack(ByteArray(47)))
        assertNull(JamOpWire.unpack(ByteArray(49)))
        assertNull(JamOpWire.unpack(ByteArray(0)))
    }

    @Test
    fun `out-of-range type and policy rejected`() {
        for (bad in intArrayOf(0, 4, -1, Int.MAX_VALUE)) {
            val bytes = JamOpWire.pack(op.copy(type = bad))
            assertNull("type $bad must be rejected", JamOpWire.unpack(bytes))
        }
        for (bad in intArrayOf(-1, 2, 255)) {
            val bytes = JamOpWire.pack(op.copy(policy = bad))
            assertNull("policy $bad must be rejected", JamOpWire.unpack(bytes))
        }
    }

    @Test
    fun `non-finite fractional index rejected`() {
        for (bad in doubleArrayOf(Double.NaN, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY)) {
            val bytes = JamOpWire.pack(op.copy(frac = bad))
            assertNull("frac $bad must be rejected", JamOpWire.unpack(bytes))
        }
    }
}
