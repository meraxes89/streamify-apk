    #[test]
    fn layout_pins_are_unique_and_documented_lanes_are_dense() {
        // Assemble the full documented lane set from the FIRST constants
        // and the block sizes — it must cover all 128 dims exactly once.
        let mut lanes: Vec<usize> = vec![
            layout::BPM,
            layout::CAMELOT_NUMBER,
            layout::CAMELOT_LETTER,
            layout::INTEGRATED_LUFS,
            layout::CREST_FACTOR_DB,
        ];
        lanes
            .extend(layout::SPECTRAL_BAND_FIRST..layout::SPECTRAL_BAND_FIRST + SPECTRAL_BAND_COUNT);
        lanes.extend([
            layout::SPECTRAL_CENTROID_KHZ,
            layout::SPECTRAL_FLATNESS,
            layout::ZERO_CROSSING_RATE,
            layout::RMS_MEAN,
            layout::DYNAMIC_RANGE,
            layout::ONSET_RATE,
            layout::BEAT_STRENGTH,
            layout::BPM_CONFIDENCE,
            layout::DANCEABILITY,
            layout::ENERGY,
            layout::VALENCE,
            layout::ACOUSTICNESS,
        ]);
        lanes.extend(layout::WAVEFORM_FIRST..layout::WAVEFORM_FIRST + WAVEFORM_BUCKET_COUNT);
        lanes.extend(layout::RESERVED_FIRST..=layout::LAYOUT_VERSION);
        lanes.sort_unstable();
        let unique = lanes.iter().collect::<std::collections::BTreeSet<_>>();
        assert_eq!(unique.len(), lanes.len(), "a lane index is used twice");
        assert_eq!(lanes.first(), Some(&0), "lane 0 is documented");
        assert_eq!(lanes.last(), Some(&127), "lane 127 is documented");
        assert_eq!(lanes.len(), 128, "documented lanes cover all 128 dims");
        // A duplicate index would silently alias a lane — the BTreeSet
        // above proves density AND uniqueness together.
    }

    #[test]
    fn wire_round_trip_is_exact() {
        let v = reference_vector();
        let wire = v.to_le_bytes();
        assert_eq!(wire.len(), ACOUSTIC_EMBEDDING_WIRE_BYTES);
        let back = AcousticEmbeddingVector::from_le_bytes(&wire).unwrap();
        assert_eq!(v, back);
        assert_eq!(back.to_le_bytes(), wire);
    }

    #[test]
    fn wire_rejects_corruption() {
        let v = reference_vector();
        let mut wire = v.to_le_bytes();
        // Wrong version header (LE byte 0 patched: 1 -> 9).
        wire[0] = 9;
        assert_eq!(
            AcousticEmbeddingVector::from_le_bytes(&wire),
            Err(EmbeddingWireError::UnsupportedVersion(9))
        );
        // Wrong length.
        assert!(matches!(
            AcousticEmbeddingVector::from_le_bytes(&wire[..100]),
            Err(EmbeddingWireError::BadLength { .. })
        ));
        // NaN lane (BPM lane = wire[4..8]).
        let mut nan_wire = v.to_le_bytes();
        nan_wire[4..8].copy_from_slice(&f32::NAN.to_le_bytes());
        assert!(matches!(
            AcousticEmbeddingVector::from_le_bytes(&nan_wire),
            Err(EmbeddingWireError::NonFiniteLane(0))
        ));
        // Non-zero reserved lane (index 100).
        let mut res_wire = v.to_le_bytes();
        res_wire[4 + 100 * 4..4 + 100 * 4 + 4].copy_from_slice(&1.0f32.to_le_bytes());
        assert_eq!(
            AcousticEmbeddingVector::from_le_bytes(&res_wire),
            Err(EmbeddingWireError::ReservedLaneNonZero)
        );
        // Version tripwire lane corrupted.
        let mut trip_wire = v.to_le_bytes();
        trip_wire[4 + layout::LAYOUT_VERSION * 4..4 + layout::LAYOUT_VERSION * 4 + 4]
            .copy_from_slice(&7.0f32.to_le_bytes());
        assert!(matches!(
            AcousticEmbeddingVector::from_le_bytes(&trip_wire),
            Err(EmbeddingWireError::VersionLaneMismatch(_))
        ));
    }

    #[test]
    fn camelot_helpers_round_trip() {
        for key in ["8A", "12B", "1b", "5A", "9B"] {
            let (n, l) = parse_camelot_key(key);
            assert_eq!(format_camelot_key(n, l), key.to_uppercase());
        }
        // Malformed input degrades to the neutral 8A.
        assert_eq!(parse_camelot_key("garbage"), (8, CamelotLetter::Major));
        assert_eq!(parse_camelot_key(""), (8, CamelotLetter::Major));
        assert_eq!(parse_camelot_key("99Z"), (12, CamelotLetter::Major));
    }

    #[test]
    fn udl_record_conversion_is_lossless() {
        let v = reference_vector();
        let record = AcousticEmbedding::from(&v);
        assert_eq!(record.version, 1);
        assert_eq!(record.dims.len(), 128);
        assert_eq!(record.bpm, 124.0);
        assert_eq!(record.camelot_number, 8);
        assert_eq!(record.camelot_letter, 0);
        assert_eq!(record.danceability, 0.69);
        let back = AcousticEmbeddingVector::from(&record);
        assert_eq!(back, v);
    }

