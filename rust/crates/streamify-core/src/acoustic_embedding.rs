        v.set_lane(layout::CREST_FACTOR_DB, 9.5);
        for i in 0..SPECTRAL_BAND_COUNT {
            v.set_lane(layout::SPECTRAL_BAND_FIRST + i, 0.1 * (i as f32 + 1.0));
        }
        v.set_lane(layout::SPECTRAL_CENTROID_KHZ, 2.4);
        v.set_lane(layout::SPECTRAL_FLATNESS, 0.18);
        v.set_lane(layout::ZERO_CROSSING_RATE, 0.09);
        v.set_lane(layout::RMS_MEAN, 0.22);
        v.set_lane(layout::DYNAMIC_RANGE, 0.44);
        v.set_lane(layout::ONSET_RATE, 3.5);
        v.set_lane(layout::BEAT_STRENGTH, 0.72);
        v.set_lane(layout::BPM_CONFIDENCE, 0.81);
        v.set_lane(layout::DANCEABILITY, 0.69);
        v.set_lane(layout::ENERGY, 0.58);
        v.set_lane(layout::VALENCE, 0.62);
        v.set_lane(layout::ACOUSTICNESS, 0.47);
