//! acoustic_embedding.rs — the versioned 128-dim acoustic embedding
//! contract (WS-D D1, AHEAD.md Wave 3).
//!
//! # The contract this module freezes
//!
//! Before WS-D the continuum engine consumed a raw `[f32; 128]` whose
//! layout was implicit and undocumented — `continuum_engine.rs` lazily
//! overloaded `vec[0]` = BPM and `vec[1]` = artist-hash, so every
//! producer had to know the folklore by heart and any lane reshuffle
//! silently corrupted the momentum vector. This module replaces the
//! folklore with a **named, versioned, layout-pinned contract**:
//!
//! * [`AcousticEmbeddingVector`] — the `#[repr(C)]` fixed-layout value
//!   type every engine lane scores against (BPM, Camelot key, LUFS,
//!   spectral bands, waveform energy, danceability proxies);
//! * [`layout`] — the named index constants of the 128 lanes (the
//!   schema doc lives at `docs/architecture/acoustic_embedding_contract_v1.md`);
//! * [`AcousticEmbedding`] — the UniFFI-facing record (the typed
//!   Kotlin / Swift currency; carries the headline scalars unpacked so
//!   shells never index raw lanes by hand).
//!
//! Identity fields (artist / track hashes) are deliberately NOT lanes:
//! they travel as explicit arguments (`commit_track`'s `artist_hash` /
//! `track_hash`), never overloaded into vector positions again.
//!
//! # Wire format (v1)
//!
//! ```text
//! [version: 4B u32 LE][dims: 128 × 4B f32 LE]   = 516 bytes exactly
//! ```
//!
//! Little-endian on every platform (the workspace `wire_le` convention).
//! [`AcousticEmbeddingVector::from_le_bytes`] validates the version and
//! that every lane is finite; unknown FUTURE versions are rejected —
//! consumers parse the version first and dispatch, they never guess.
//!
//! # Cross-language pinning
//!
//! The exact layout is pinned layout-for-layout by three contract
//! suites reading one shared golden fixture
//! (`fixtures/acoustic_embedding/v1_reference.bin`):
//!
//! * Rust — `tests` in this module (wire round-trip + lane pins);
//! * Kotlin — `app/src/test/.../AcousticEmbeddingContractTest.kt` (JVM,
//!   reads the same bytes from `app/src/test/resources`);
//! * Swift — `iosApp/Tests/StreamifyIOSTests/EngineTests` (reads the
//!   same bytes from the test bundle resources).
//!
//! The fixture is generated by `cargo test -p streamify-core
//! acoustic_embedding` (see `write_reference_fixture`), and any lane
//! renumbering fails all three suites at once — that is the point.

/// The embedding contract's layout version (bump ONLY on a breaking
/// lane renumbering; additive lanes reserved today stay reserved
/// forever and a v2 ships as a NEW record type per the version policy
/// in the schema doc).
pub const ACOUSTIC_EMBEDDING_VERSION: u32 = 1;

/// The fixed lane count. This is the contract's name: **128**.
pub const ACOUSTIC_EMBEDDING_DIM: usize = 128;

/// Wire size: 4B version header + 128 × 4B lanes.
pub const ACOUSTIC_EMBEDDING_WIRE_BYTES: usize = 4 + ACOUSTIC_EMBEDDING_DIM * 4;

/// Number of spectral band lanes (one per `StudioEqualizer` octave).
pub const SPECTRAL_BAND_COUNT: usize = 10;

/// Number of waveform envelope lanes (peak-preserving RMS buckets).
pub const WAVEFORM_BUCKET_COUNT: usize = 64;

// Compile-time layout pins: the struct must be exactly 516 bytes with
// 4-byte alignment — Kotlin/Swift pin the same numbers from the fixture.
const _: () = assert!(ACOUSTIC_EMBEDDING_WIRE_BYTES == 516);

/// Named lane indices of the 128-dim embedding — the SCHEMA.
///
/// Lanes `[RESERVED_FIRST, LAYOUT_VERSION)` are reserved (zero in v1)
/// so additive v1.x growth never renumbers a shipped lane.
pub mod layout {
    /// Tempo estimate in BPM (40..=240; 0 = unknown).
    pub const BPM: usize = 0;
    /// Camelot wheel number 1..=12.
    pub const CAMELOT_NUMBER: usize = 1;
    /// Camelot letter: 0 = A (major), 1 = B (minor).
    pub const CAMELOT_LETTER: usize = 2;
    /// ITU-R BS.1770-4 integrated loudness, LUFS (-70..=0).
    pub const INTEGRATED_LUFS: usize = 3;
    /// Crest factor: peak / RMS (dB, 0..=24).
    pub const CREST_FACTOR_DB: usize = 4;
    /// First of 10 octave-band energies (31.25 Hz .. 16 kHz), 0..=1.
    pub const SPECTRAL_BAND_FIRST: usize = 5;
    /// Spectral centroid in kHz (0..=12).
    pub const SPECTRAL_CENTROID_KHZ: usize = 15;
    /// Spectral flatness (Wiener entropy proxy), 0..=1.
    pub const SPECTRAL_FLATNESS: usize = 16;
    /// Zero-crossing rate per sample, 0..=1.
    pub const ZERO_CROSSING_RATE: usize = 17;
    /// Mean RMS amplitude, 0..=1.
    pub const RMS_MEAN: usize = 18;
    /// Dynamic range: P95 - P10 waveform amplitude spread, 0..=1.
    pub const DYNAMIC_RANGE: usize = 19;
    /// Onset rate: detected onsets per second, 0..=12.
    pub const ONSET_RATE: usize = 20;
    /// Beat strength: normalized autocorrelation peak, 0..=1.
    pub const BEAT_STRENGTH: usize = 21;
    /// Tempo-estimation confidence, 0..=1.
    pub const BPM_CONFIDENCE: usize = 22;
    /// Composite danceability proxy, 0..=1.
    pub const DANCEABILITY: usize = 23;
    /// Composite perceived energy proxy, 0..=1.
    pub const ENERGY: usize = 24;
    /// Brightness / major-ness valence proxy, 0..=1.
    pub const VALENCE: usize = 25;
    /// Harmonic-vs-noisy acousticness proxy, 0..=1.
    pub const ACOUSTICNESS: usize = 26;
    /// First of 64 peak-preserving RMS waveform buckets, 0..=1.
    pub const WAVEFORM_FIRST: usize = 27;
    /// First reserved lane (zero in v1, reserved for additive v1.x).
    pub const RESERVED_FIRST: usize = 91;
    /// Lane carrying the layout version as f32 (1.0) — a self-describing
    /// tripwire: a misaligned buffer reads garbage here, not a plausible
    /// feature.
    pub const LAYOUT_VERSION: usize = 127;
}

/// Camelot letter domain: `A` = major side of the wheel, `B` = minor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum CamelotLetter {
    /// `A` — the major side (e.g. 8A = C major).
    Major = 0,
    /// `B` — the minor side (e.g. 1A = A minor on the Camelot wheel).
    Minor = 1,
}

impl CamelotLetter {
    /// The wheel letter (`A` / `B`).
    pub fn as_char(self) -> char {
        match self {
            CamelotLetter::Major => 'A',
            CamelotLetter::Minor => 'B',
        }
    }

    /// Parse the wheel letter (`A`/`a` → Major, `B`/`b` → Minor).
    pub fn parse(c: char) -> Option<Self> {
        match c.to_ascii_uppercase() {
            'A' => Some(CamelotLetter::Major),
            'B' => Some(CamelotLetter::Minor),
            _ => None,
        }
    }
}

/// Parse a Camelot key string (`"8A"`, `"12b"`, `"1B"`) into the
/// `(number, letter)` domain. Malformed input clamps to the neutral
/// `(8, Major)` exactly like the historical `neuro_queue` parser, so
/// upstream metadata rot degrades to "no harmonic signal" instead of
/// panicking.
pub fn parse_camelot_key(key: &str) -> (u8, CamelotLetter) {
    let clean = key.trim().to_uppercase();
    let num: u8 = clean
        .chars()
        .filter(|c| c.is_ascii_digit())
        .collect::<String>()
        .parse()
        .unwrap_or(8);
    let letter = clean
        .chars()
        .find_map(CamelotLetter::parse)
        .unwrap_or(CamelotLetter::Major);
    (num.clamp(1, 12), letter)
}

/// Format a `(number, letter)` pair back onto the wheel (`8A`).
pub fn format_camelot_key(number: u8, letter: CamelotLetter) -> String {
    format!("{}{}", number.clamp(1, 12), letter.as_char())
}

/// The `#[repr(C)]` fixed-layout 128-dim embedding value — the engine
/// lane's scoring currency. `repr(C)` + the compile-time size pins make
/// the memory layout a frozen contract, not an accident.
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(C)]
pub struct AcousticEmbeddingVector {
    /// Layout version — always [`ACOUSTIC_EMBEDDING_VERSION`] for
    /// values built by this crate; [`from_le_bytes`] rejects others.
    pub version: u32,
    /// The 128 lanes, addressed ONLY through [`layout`] constants.
    pub dims: [f32; ACOUSTIC_EMBEDDING_DIM],
}

impl AcousticEmbeddingVector {
    /// A v1 vector with every lane at its neutral zero (BPM lane 0 =
    /// unknown tempo; the scorer treats it as "no signal").
    pub fn neutral() -> Self {
        Self {
            version: ACOUSTIC_EMBEDDING_VERSION,
            dims: [0.0; ACOUSTIC_EMBEDDING_DIM],
        }
    }

    /// Read one lane by [`layout`] index.
    pub fn lane(&self, index: usize) -> f32 {
        self.dims.get(index).copied().unwrap_or(0.0)
    }

    /// Write one lane by [`layout`] index (no-op when out of range —
    /// callers pass `layout` constants, which are always in range).
    pub fn set_lane(&mut self, index: usize, value: f32) {
        if let Some(slot) = self.dims.get_mut(index) {
            *slot = value;
        }
    }

    /// Headline tempo (BPM; 0 = unknown).
    pub fn bpm(&self) -> f32 {
        self.lane(layout::BPM)
    }

    /// Camelot key as `(number, letter)`.
    pub fn camelot(&self) -> (u8, CamelotLetter) {
        let number = self.lane(layout::CAMELOT_NUMBER).clamp(1.0, 12.0) as u8;
        let letter = if self.lane(layout::CAMELOT_LETTER) >= 0.5 {
            CamelotLetter::Minor
        } else {
            CamelotLetter::Major
        };
        (number, letter)
    }

    /// Integrated loudness (LUFS).
    pub fn integrated_lufs(&self) -> f32 {
        self.lane(layout::INTEGRATED_LUFS)
    }

    /// Danceability composite (0..=1).
    pub fn danceability(&self) -> f32 {
        self.lane(layout::DANCEABILITY)
    }

    /// Energy composite (0..=1).
    pub fn energy(&self) -> f32 {
        self.lane(layout::ENERGY)
    }

    /// Valence composite (0..=1).
    pub fn valence(&self) -> f32 {
        self.lane(layout::VALENCE)
    }

    /// Acousticness composite (0..=1).
    pub fn acousticness(&self) -> f32 {
        self.lane(layout::ACOUSTICNESS)
    }

    /// Serialize to the frozen little-endian wire image (516 bytes).
    pub fn to_le_bytes(&self) -> [u8; ACOUSTIC_EMBEDDING_WIRE_BYTES] {
        let mut out = [0u8; ACOUSTIC_EMBEDDING_WIRE_BYTES];
        out[..4].copy_from_slice(&self.version.to_le_bytes());
        for (i, lane) in self.dims.iter().enumerate() {
            out[4 + i * 4..4 + i * 4 + 4].copy_from_slice(&lane.to_le_bytes());
        }
        out
    }

    /// Parse the frozen little-endian wire image. Rejects wrong sizes,
    /// unknown versions, non-finite lanes and non-zero reserved lanes.
    pub fn from_le_bytes(bytes: &[u8]) -> Result<Self, EmbeddingWireError> {
        if bytes.len() != ACOUSTIC_EMBEDDING_WIRE_BYTES {
            return Err(EmbeddingWireError::BadLength {
                expected: ACOUSTIC_EMBEDDING_WIRE_BYTES,
                actual: bytes.len(),
            });
        }
        let version = u32::from_le_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]);
        if version != ACOUSTIC_EMBEDDING_VERSION {
            return Err(EmbeddingWireError::UnsupportedVersion(version));
        }
        let mut dims = [0.0f32; ACOUSTIC_EMBEDDING_DIM];
        for (i, lane) in dims.iter_mut().enumerate() {
            let raw = f32::from_le_bytes([
                bytes[4 + i * 4],
                bytes[4 + i * 4 + 1],
                bytes[4 + i * 4 + 2],
                bytes[4 + i * 4 + 3],
            ]);
            if !raw.is_finite() {
                return Err(EmbeddingWireError::NonFiniteLane(i));
            }
            *lane = raw;
        }
        if dims[layout::LAYOUT_VERSION] != ACOUSTIC_EMBEDDING_VERSION as f32 {
            return Err(EmbeddingWireError::VersionLaneMismatch(
                dims[layout::LAYOUT_VERSION],
            ));
        }
        if dims[layout::RESERVED_FIRST..layout::LAYOUT_VERSION]
            .iter()
            .any(|&v| v != 0.0)
        {
            return Err(EmbeddingWireError::ReservedLaneNonZero);
        }
        Ok(Self { version, dims })
    }

    /// Structural validity for freshly built vectors (finite lanes,
    /// version tripwire, zero reserved lanes).
    pub fn validate(&self) -> Result<(), EmbeddingWireError> {
        if self.version != ACOUSTIC_EMBEDDING_VERSION {
            return Err(EmbeddingWireError::UnsupportedVersion(self.version));
        }
        if let Some(i) = self.dims.iter().position(|v| !v.is_finite()) {
            return Err(EmbeddingWireError::NonFiniteLane(i));
        }
        if self.dims[layout::LAYOUT_VERSION] != ACOUSTIC_EMBEDDING_VERSION as f32 {
            return Err(EmbeddingWireError::VersionLaneMismatch(
                self.dims[layout::LAYOUT_VERSION],
            ));
        }
        if self.dims[layout::RESERVED_FIRST..layout::LAYOUT_VERSION]
            .iter()
            .any(|&v| v != 0.0)
        {
            return Err(EmbeddingWireError::ReservedLaneNonZero);
        }
        Ok(())
    }
}

/// Wire-format validation failures.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum EmbeddingWireError {
    /// Buffer is not exactly 516 bytes.
    BadLength { expected: usize, actual: usize },
    /// Version header is not the supported v1.
    UnsupportedVersion(u32),
    /// A lane is NaN / ±inf.
    NonFiniteLane(usize),
    /// The `LAYOUT_VERSION` tripwire lane does not read 1.0.
    VersionLaneMismatch(f32),
    /// A reserved lane is non-zero (schema violation).
    ReservedLaneNonZero,
}

impl core::fmt::Display for EmbeddingWireError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            EmbeddingWireError::BadLength { expected, actual } => {
                write!(f, "wire length {actual}, expected {expected}")
            }
            EmbeddingWireError::UnsupportedVersion(v) => {
                write!(
                    f,
                    "unsupported embedding version {v} (supported: {ACOUSTIC_EMBEDDING_VERSION})"
                )
            }
            EmbeddingWireError::NonFiniteLane(i) => write!(f, "lane {i} is non-finite"),
            EmbeddingWireError::VersionLaneMismatch(v) => {
                write!(f, "layout-version lane reads {v}, expected 1.0")
            }
            EmbeddingWireError::ReservedLaneNonZero => write!(f, "reserved lane is non-zero"),
        }
    }
}

impl std::error::Error for EmbeddingWireError {}

/// The UniFFI-facing embedding record: the full 128-lane vector plus
/// the headline scalars unpacked (the Kotlin / Swift currency — shells
/// read `bpm` / `camelotNumber` / … without indexing lanes by hand).
///
/// `dims.len()` is always [`ACOUSTIC_EMBEDDING_DIM`]; the record is
/// built from [`AcousticEmbeddingVector`] and converts back losslessly.
#[derive(Debug, Clone, PartialEq)]
pub struct AcousticEmbedding {
    /// Layout version (always 1 for this contract).
    pub version: u32,
    /// All 128 lanes, in [`layout`] order.
    pub dims: Vec<f32>,
    /// Tempo estimate in BPM (0 = unknown).
    pub bpm: f32,
    /// Camelot wheel number 1..=12.
    pub camelot_number: u32,
    /// Camelot letter: 0 = A (major), 1 = B (minor).
    pub camelot_letter: u32,
    /// Integrated loudness (LUFS).
    pub integrated_lufs: f32,
    /// Danceability composite (0..=1).
    pub danceability: f32,
    /// Energy composite (0..=1).
    pub energy: f32,
    /// Valence composite (0..=1).
    pub valence: f32,
    /// Acousticness composite (0..=1).
    pub acousticness: f32,
}

impl From<&AcousticEmbeddingVector> for AcousticEmbedding {
    fn from(v: &AcousticEmbeddingVector) -> Self {
        let (camelot_number, camelot_letter) = v.camelot();
        AcousticEmbedding {
            version: v.version,
            dims: v.dims.to_vec(),
            bpm: v.bpm(),
            camelot_number: camelot_number as u32,
            camelot_letter: camelot_letter as u32,
            integrated_lufs: v.integrated_lufs(),
            danceability: v.danceability(),
            energy: v.energy(),
            valence: v.valence(),
            acousticness: v.acousticness(),
        }
    }
}

impl From<&AcousticEmbedding> for AcousticEmbeddingVector {
    fn from(r: &AcousticEmbedding) -> Self {
        let mut dims = [0.0f32; ACOUSTIC_EMBEDDING_DIM];
        for (i, lane) in r.dims.iter().take(ACOUSTIC_EMBEDDING_DIM).enumerate() {
            dims[i] = *lane;
        }
        AcousticEmbeddingVector {
            version: r.version,
            dims,
        }
    }
}

